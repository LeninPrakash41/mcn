"""
Installable web app (PWA) files for generated frontends: a web manifest,
icons and a service worker that caches the app shell (never API data), so
the app can be added to the home screen on Android and iOS.
"""

from __future__ import annotations

import colorsys
import json
import struct
import zlib
from pathlib import Path
from typing import List


def hsl_to_hex(hsl: str) -> str:
    """"221.2 83.2% 53.3%" → "#2563eb"."""
    try:
        h, s_, l_ = hsl.replace("%", "").split()
        r, g, b = colorsys.hls_to_rgb(float(h) / 360, float(l_) / 100, float(s_) / 100)
        return "#{:02x}{:02x}{:02x}".format(round(r * 255), round(g * 255), round(b * 255))
    except (ValueError, TypeError):
        return "#2563eb"


def _png(size: int, color: str) -> bytes:
    """A square app icon: theme colour with a white ring (no dependencies)."""
    cr, cg, cb = (int(color[i:i + 2], 16) for i in (1, 3, 5))
    c, outer, inner = size / 2, size * 0.30, size * 0.20
    rows = []
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            d = ((x - c + 0.5) ** 2 + (y - c + 0.5) ** 2) ** 0.5
            row += bytes((255, 255, 255) if inner <= d <= outer else (cr, cg, cb))
        rows.append(bytes(row))
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b""))


SERVICE_WORKER = """// Service worker — generated by `mcn build`.
// Caches the app's own files so it opens fast and installs on phones.
// API calls (a different origin) are never cached.
const CACHE = "mcn-app-v1"

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(["/", "/manifest.webmanifest"])))
  self.skipWaiting()
})

self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys().then((keys) =>
    Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))))
  self.clients.claim()
})

self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url)
  if (event.request.method !== "GET" || url.origin !== self.location.origin) return
  if (event.request.mode === "navigate") {
    // Pages: network first, fall back to the cached app shell when offline
    event.respondWith(fetch(event.request).catch(() => caches.match("/")))
    return
  }
  // Built assets have hashed names: cache first
  event.respondWith(caches.match(event.request).then((hit) => hit || fetch(event.request).then((res) => {
    if (res.ok) caches.open(CACHE).then((c) => c.put(event.request, res.clone()))
    return res
  })))
})
"""


def write_pwa(out: Path, title: str, primary_hsl: str) -> List[Path]:
    public = out / "public"
    public.mkdir(parents=True, exist_ok=True)
    color = hsl_to_hex(primary_hsl)
    files = {
        "manifest.webmanifest": json.dumps({
            "name": title, "short_name": title[:12], "start_url": "/", "scope": "/",
            "display": "standalone", "background_color": "#ffffff", "theme_color": color,
            "icons": [
                {"src": "/icon-192.png", "sizes": "192x192", "type": "image/png"},
                {"src": "/icon-512.png", "sizes": "512x512", "type": "image/png"},
                {"src": "/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
            ],
        }, indent=2),
        "sw.js": SERVICE_WORKER,
    }
    written = []
    for name, text in files.items():
        (public / name).write_text(text)
        written.append(public / name)
    for size in (192, 512):
        (public / f"icon-{size}.png").write_bytes(_png(size, color))
        written.append(public / f"icon-{size}.png")
    return written


def index_head(title: str, primary_hsl: str) -> str:
    color = hsl_to_hex(primary_hsl)
    return (f'    <meta name="theme-color" content="{color}" />\n'
            '    <link rel="manifest" href="/manifest.webmanifest" />\n'
            '    <link rel="icon" type="image/png" href="/icon-192.png" />\n'
            '    <link rel="apple-touch-icon" href="/icon-192.png" />\n'
            '    <meta name="apple-mobile-web-app-capable" content="yes" />\n'
            '    <meta name="mobile-web-app-capable" content="yes" />\n'
            f'    <meta name="apple-mobile-web-app-title" content="{title[:12]}" />\n')
