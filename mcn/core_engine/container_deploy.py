"""
`mcn deploy --target aws` and `mcn deploy --target cloudflare`: put the web app and its
MCN backend online in a container, in your own cloud account.

    aws         AWS App Runner: auto-scaling, HTTPS, in the region you choose (--region).
                Needs the AWS CLI (signed in) and Docker.
    cloudflare  Cloudflare Containers: the web app is served from Cloudflare's edge and
                /api runs in a container. Needs Node.js, Docker and a Cloudflare account
                (CLOUDFLARE_API_TOKEN, or `npx wrangler login`).

Both build the same image (see container_app.py). The project is staged in
.mcn/deploy/<name>-<target>/ inside the workspace. Containers on these hosts lose
their disk when they restart, so keep data in PostgreSQL: put DATABASE_URL in .env.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from pathlib import Path
from typing import Callable, Dict, List, Optional

from .vercel_deploy import DeployError, _compile_ui, _project_env
from . import vercel_deploy

# Also forwarded to container deployments (on top of vercel_deploy.FORWARDED)
EXTRA_FORWARDED = ("MCN_SSO_ISSUER", "MCN_SSO_CLIENT_ID", "MCN_SSO_CLIENT_SECRET", "MCN_SSO_REDIRECT_URL",
                   "MCN_SSO_ALLOWED_DOMAINS", "MCN_SSO_ROLES_CLAIM", "MCN_AUDIT_WEBHOOK", "MCN_AUDIT_WEBHOOK_TOKEN")

DOCKERFILE = '''# Generated by `mcn deploy`. Builds the web app, then serves it (/) and the MCN API (/api).
FROM node:20-slim AS web
WORKDIR /app/frontend
COPY frontend/package.json ./
RUN npm install --no-audit --no-fund --loglevel=error
COPY frontend/ ./
RUN npm run build

FROM python:3.12-slim
ENV PYTHONUNBUFFERED=1 PORT=8080 MCN_DATA_DIR=/data
RUN pip install --no-cache-dir "mcn-lang[postgres,sso] @ {source}"
WORKDIR /app
COPY backend/ backend/
COPY --from=web /app/frontend/dist frontend/dist
EXPOSE 8080
CMD ["python", "-m", "mcn.core_engine.container_app", "/app"]
'''

DOCKERFILE_API_ONLY = '''# Generated by `mcn deploy`. Serves the MCN API at /api.
FROM python:3.12-slim
ENV PYTHONUNBUFFERED=1 PORT=8080 MCN_DATA_DIR=/data
RUN pip install --no-cache-dir "mcn-lang[postgres,sso] @ {source}"
WORKDIR /app
COPY backend/ backend/
EXPOSE 8080
CMD ["python", "-m", "mcn.core_engine.container_app", "/app"]
'''

WORKER_TS = '''// Generated by `mcn deploy --target cloudflare`.
// The web app is served as static assets; /api/* goes to the MCN container.
import { Container } from "@cloudflare/containers"

interface Env {
  MCN_APP: DurableObjectNamespace<MCNApp>
  ASSETS: Fetcher
  [setting: string]: unknown
}

const SETTINGS = {settings}

export class MCNApp extends Container<Env> {
  defaultPort = 8080
  sleepAfter = "15m"

  constructor(ctx: DurableObjectState<{}>, env: Env) {
    super(ctx, env)
    // Settings and secrets set with `wrangler secret` reach the container as environment variables
    const vars: Record<string, string> = {}
    for (const key of SETTINGS) {
      const value = env[key]
      if (typeof value === "string" && value) vars[key] = value
    }
    this.envVars = vars
  }
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url)
    if (url.pathname === "/api" || url.pathname.startsWith("/api/")) {
      // One instance, so every request sees the same app state
      return env.MCN_APP.getByName("main").fetch(request)
    }
    return env.ASSETS.fetch(request)
  },
}
'''


def _safe_name(name: str) -> str:
    return re.sub(r"[^a-z0-9-]+", "-", name.lower()).strip("-")[:40] or "mcn-app"


def stage(workspace, name: str, target: str) -> Path:
    """Write the container project for `target` ("aws" or "cloudflare") and return its folder."""
    if target not in ("aws", "cloudflare"):
        raise DeployError(f"Unknown target {target!r}")
    ws = Path(workspace).resolve()
    backend = ws / "backend"
    if not list(backend.rglob("*.mcn")):
        raise DeployError(f"No backend/*.mcn in {ws}. Container deploys need a backend with a service.")
    if not any("service " in f.read_text(encoding="utf-8") for f in backend.rglob("*.mcn")):
        raise DeployError("The backend has no `service` block, so there's no API to deploy")
    name = _safe_name(name)
    out = ws / ".mcn" / "deploy" / f"{name}-{target}"
    out.mkdir(parents=True, exist_ok=True)
    for child in out.iterdir():
        if child.name not in (".wrangler", "node_modules"):
            shutil.rmtree(child) if child.is_dir() else child.unlink()

    shutil.copytree(backend, out / "backend", ignore=shutil.ignore_patterns("*.db", "*.log", "__pycache__"))
    has_frontend = False
    ui = ws / "ui" / "app.mcn"
    if ui.exists():
        _compile_ui(ui, out / "frontend", backend / "main.mcn")
        has_frontend = True
    elif (ws / "frontend" / "package.json").exists():
        shutil.copytree(ws / "frontend", out / "frontend", ignore=shutil.ignore_patterns("node_modules", "dist", "*.log"))
        has_frontend = True
    if has_frontend:
        (out / "frontend" / ".env.production").write_text("VITE_API_URL=/api\n", encoding="utf-8")

    api_only = target == "cloudflare" or not has_frontend     # Cloudflare serves the web app itself
    dockerfile = (DOCKERFILE_API_ONLY if api_only else DOCKERFILE).format(source=vercel_deploy.SOURCE)
    SOURCE = vercel_deploy.SOURCE
    if Path(SOURCE).is_dir():
        # MCN_DEPLOY_SOURCE=<a local MCN checkout>: install that copy (for testing unreleased changes)
        shutil.copytree(SOURCE, out / "mcn-src", ignore=shutil.ignore_patterns(
            ".git", "node_modules", "__pycache__", "tests", ".mcn", "*.db", "dist", "build", "*.egg-info"))
        dockerfile = dockerfile.replace(f'RUN pip install --no-cache-dir "mcn-lang[postgres,sso] @ {SOURCE}"',
                                        'COPY mcn-src /tmp/mcn-src\nRUN pip install --no-cache-dir "/tmp/mcn-src[postgres,sso]"')
    (out / "Dockerfile").write_text(dockerfile, encoding="utf-8")
    (out / ".dockerignore").write_text("frontend/node_modules\nfrontend/dist\nnode_modules\n.wrangler\n*.db\n",
                                       encoding="utf-8")
    if target == "cloudflare":
        _stage_cloudflare(out, name, has_frontend)
    return out


def _settings_keys() -> List[str]:
    from .vercel_deploy import FORWARDED
    return sorted(set(FORWARDED) | set(EXTRA_FORWARDED) | {"MCN_AUTH_SECRET"})


def _stage_cloudflare(out: Path, name: str, has_frontend: bool) -> None:
    (out / "src").mkdir(exist_ok=True)
    (out / "src" / "index.ts").write_text(WORKER_TS.replace("{settings}", json.dumps(_settings_keys())),
                                          encoding="utf-8")
    config: Dict = {
        "$schema": "node_modules/wrangler/config-schema.json",
        "name": name,
        "main": "src/index.ts",
        "compatibility_date": "2026-06-01",
        "containers": [{"class_name": "MCNApp", "image": "./Dockerfile", "max_instances": 1}],
        "durable_objects": {"bindings": [{"name": "MCN_APP", "class_name": "MCNApp"}]},
        "migrations": [{"tag": "v1", "new_sqlite_classes": ["MCNApp"]}],
        "observability": {"enabled": True},
    }
    if has_frontend:
        config["assets"] = {"directory": "./frontend/dist", "binding": "ASSETS",
                            "not_found_handling": "single-page-application", "run_worker_first": ["/api/*"]}
    (out / "wrangler.jsonc").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    (out / "package.json").write_text(json.dumps({
        "name": name, "private": True, "type": "module",
        "scripts": {"deploy": "wrangler deploy"},
        "dependencies": {"@cloudflare/containers": "^0.3.7"},
        "devDependencies": {"wrangler": "^4.160.0", "@cloudflare/workers-types": "^5.20261110.1",
                            "typescript": "^5.5.3"},
    }, indent=2) + "\n", encoding="utf-8")
    (out / "tsconfig.json").write_text(json.dumps({
        "compilerOptions": {"target": "ES2022", "lib": ["ES2022"], "module": "ES2022", "moduleResolution": "bundler",
                            "strict": True, "skipLibCheck": True, "types": ["@cloudflare/workers-types"], "noEmit": True},
        "include": ["src"],
    }, indent=2) + "\n", encoding="utf-8")


# ── Running the cloud CLIs ────────────────────────────────────────────────────

Runner = Callable[..., subprocess.CompletedProcess]


def _run(cmd: List[str], cwd: Path, input_text: Optional[str] = None, env: Optional[Dict[str, str]] = None,
         capture: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd, input=input_text, text=True, env={**os.environ, **(env or {})},
                          stdout=subprocess.PIPE if capture else None, stderr=subprocess.PIPE if capture else None)


def _need(tool: str, hint: str) -> None:
    if not shutil.which(tool):
        raise DeployError(f"This deploy needs `{tool}`. {hint}")


def _check(proc: subprocess.CompletedProcess, what: str) -> str:
    if proc.returncode != 0:
        detail = ((proc.stderr or "") + (proc.stdout or "")).strip().splitlines()[-3:]
        raise DeployError(f"{what} failed" + (": " + " ".join(detail) if detail else ""))
    return (proc.stdout or "").strip()


def _warn_about_storage(env: Dict[str, str], log) -> None:
    if "DATABASE_URL" not in env:
        log("Note: no DATABASE_URL in .env, so the app uses SQLite inside the container, which is reset when "
            "the container restarts. Add a PostgreSQL DATABASE_URL to keep data.")


def deploy_aws(workspace, name: str, region: Optional[str] = None, log=print, run: Runner = _run) -> Dict[str, object]:
    """Build the image, push it to Amazon ECR, and create or update an App Runner service."""
    _need("aws", "Install the AWS CLI and run `aws configure` (or `aws sso login`).")
    _need("docker", "Install Docker Desktop and start it.")
    ws = Path(workspace).resolve()
    out = stage(ws, name, "aws")
    env = _project_env(ws)
    env.update(_extra_env(ws))
    service = _safe_name(name)
    region = region or os.environ.get("AWS_REGION") or os.environ.get("AWS_DEFAULT_REGION") or "us-east-1"
    aws = ["aws", "--region", region, "--output", "json"]
    _warn_about_storage(env, log)

    account = json.loads(_check(run(aws + ["sts", "get-caller-identity"], out), "Checking your AWS sign-in"))["Account"]
    registry = f"{account}.dkr.ecr.{region}.amazonaws.com"
    image = f"{registry}/{service}:latest"

    log(f"Preparing the image repository in {region}…")
    if run(aws + ["ecr", "describe-repositories", "--repository-names", service], out).returncode != 0:
        _check(run(aws + ["ecr", "create-repository", "--repository-name", service,
                          "--image-scanning-configuration", "scanOnPush=true"], out), "Creating the ECR repository")
    password = _check(run(aws + ["ecr", "get-login-password"], out), "Signing in to ECR")
    _check(run(["docker", "login", "--username", "AWS", "--password-stdin", registry], out, input_text=password),
           "Docker sign-in to ECR")
    log("Building the image (the first build takes a few minutes)…")
    _check(run(["docker", "build", "--platform", "linux/amd64", "-t", image, "."], out, capture=False), "Building the image")
    _check(run(["docker", "push", image], out, capture=False), "Pushing the image")

    role_arn = _apprunner_role(aws, out, run)
    source = {
        "ImageRepository": {
            "ImageIdentifier": image, "ImageRepositoryType": "ECR",
            "ImageConfiguration": {"Port": "8080", "RuntimeEnvironmentVariables": env},
        },
        "AutoDeploymentsEnabled": False,
        "AuthenticationConfiguration": {"AccessRoleArn": role_arn},
    }
    health = {"Protocol": "HTTP", "Path": "/api/", "Interval": 10, "Timeout": 5,
              "HealthyThreshold": 1, "UnhealthyThreshold": 5}
    services = json.loads(_check(run(aws + ["apprunner", "list-services"], out), "Listing App Runner services"))
    existing = next((s for s in services.get("ServiceSummaryList", []) if s.get("ServiceName") == service), None)
    if existing:
        log(f"Updating App Runner service {service}…")
        result = json.loads(_check(run(aws + ["apprunner", "update-service", "--service-arn", existing["ServiceArn"],
                                              "--source-configuration", json.dumps(source),
                                              "--health-check-configuration", json.dumps(health)], out),
                                   "Updating the App Runner service"))
    else:
        log(f"Creating App Runner service {service}…")
        result = json.loads(_check(run(aws + ["apprunner", "create-service", "--service-name", service,
                                              "--source-configuration", json.dumps(source),
                                              "--health-check-configuration", json.dumps(health),
                                              "--instance-configuration", json.dumps({"Cpu": "1 vCPU", "Memory": "2 GB"})],
                                             out), "Creating the App Runner service"))
    url = "https://" + result["Service"]["ServiceUrl"]
    return {"url": url, "region": region, "folder": str(out), "env": sorted(env), "image": image}


def _apprunner_role(aws: List[str], out: Path, run: Runner) -> str:
    """The IAM role App Runner uses to pull images from ECR (created once per account)."""
    role = "MCNAppRunnerECRAccess"
    found = run(aws + ["iam", "get-role", "--role-name", role], out)
    if found.returncode == 0:
        return json.loads(found.stdout)["Role"]["Arn"]
    trust = {"Version": "2012-10-17", "Statement": [{"Effect": "Allow", "Action": "sts:AssumeRole",
             "Principal": {"Service": "build.apprunner.amazonaws.com"}}]}
    created = json.loads(_check(run(aws + ["iam", "create-role", "--role-name", role,
                                           "--assume-role-policy-document", json.dumps(trust)], out),
                                "Creating the App Runner access role"))
    _check(run(aws + ["iam", "attach-role-policy", "--role-name", role, "--policy-arn",
                      "arn:aws:iam::aws:policy/service-role/AWSAppRunnerServicePolicyForECRAccess"], out),
           "Allowing App Runner to read ECR")
    return created["Role"]["Arn"]


def _extra_env(ws: Path) -> Dict[str, str]:
    env: Dict[str, str] = {}
    dotenv = ws / ".env"
    if dotenv.exists():
        for line in dotenv.read_text(encoding="utf-8").splitlines():
            key, sep, value = line.strip().partition("=")
            if sep and key.strip() in EXTRA_FORWARDED and value.strip():
                env[key.strip()] = value.strip().strip('"').strip("'")
    return env


def deploy_cloudflare(workspace, name: str, log=print, run: Runner = _run) -> Dict[str, object]:
    """Build the web app, deploy the Worker and container with Wrangler, then set the app's settings as secrets."""
    _need("npx", "Install Node.js from https://nodejs.org")
    _need("docker", "Install Docker Desktop and start it (Wrangler builds the container image with it).")
    ws = Path(workspace).resolve()
    out = stage(ws, name, "cloudflare")
    env = _project_env(ws)
    env.update(_extra_env(ws))
    _warn_about_storage(env, log)

    log("Installing the deploy tools…")
    _check(run(["npm", "install", "--no-audit", "--no-fund", "--loglevel=error"], out), "npm install")
    if (out / "frontend" / "package.json").exists():
        log("Building the web app…")
        _check(run(["npm", "install", "--no-audit", "--no-fund", "--loglevel=error"], out / "frontend"),
               "Installing the web app's packages")
        _check(run(["npm", "run", "build"], out / "frontend"), "Building the web app")
    log("Deploying to Cloudflare (the first container build takes a few minutes)…")
    proc = run(["npx", "wrangler", "deploy"], out)
    text = _check(proc, "wrangler deploy")
    urls = re.findall(r"https://[\w.-]+\.workers\.dev", text)
    if env:
        secrets_file = out / ".secrets.json"
        secrets_file.write_text(json.dumps(env), encoding="utf-8")
        os.chmod(secrets_file, 0o600)
        try:
            _check(run(["npx", "wrangler", "secret", "bulk", str(secrets_file)], out), "Setting the app's settings")
        finally:
            secrets_file.unlink(missing_ok=True)
    return {"url": urls[-1] if urls else None, "folder": str(out), "env": sorted(env)}
