"""
`mcn deploy --target vercel`: put the React app and its MCN backend on Vercel.

The web app is served as static files and the backend runs as a Vercel
function at /api, so one URL serves both. The project is staged in
.mcn/deploy/<name>/ inside the workspace and uploaded with the Vercel CLI.
"""
from __future__ import annotations

import contextlib
import io
import json
import os
import re
import secrets
import shutil
import subprocess
from pathlib import Path
from typing import Dict, List, Optional

SOURCE = os.environ.get("MCN_DEPLOY_SOURCE", "https://github.com/LeninPrakash41/mcn/archive/refs/heads/main.tar.gz")

# Settings forwarded to the deployment when they're in the project's .env file
FORWARDED = ("ANTHROPIC_API_KEY", "MCN_AI_MODEL", "MCN_API_TOKEN", "MCN_CORS_ORIGINS", "MCN_RATE_LIMIT",
             "OPENAI_API_KEY", "DATABASE_URL", "MCN_MQTT_URL", "MCN_MQTT_USER", "MCN_MQTT_PASSWORD")

API_INDEX = '''# Generated by `mcn deploy --target vercel`. Serves backend/*.mcn at /api.
from pathlib import Path

from mcn.core_engine.vercel_app import create_app

app = create_app(Path(__file__).resolve().parent.parent)
'''


class DeployError(Exception):
    pass


def _vercel_json(has_frontend: bool) -> dict:
    config: Dict = {
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "functions": {"api/index.py": {"includeFiles": "backend/**", "maxDuration": 30}},
        "rewrites": [{"source": "/api/(.*)", "destination": "/api/index"}],
    }
    if has_frontend:
        config.update({
            "framework": None,
            "installCommand": "cd frontend && npm install",
            "buildCommand": "cd frontend && npm run build",
            "outputDirectory": "frontend/dist",
        })
        config["rewrites"].append({"source": "/((?!api/).*)", "destination": "/index.html"})
    return config


def _compile_ui(ui: Path, out: Path, backend_main: Path) -> None:
    from .mcn_interpreter import MCNInterpreter
    from .ui_compiler import UICompiler, endpoints_from_backend
    interp = MCNInterpreter()
    with contextlib.redirect_stdout(io.StringIO()):
        interp.execute(ui.read_text(encoding="utf-8"), quiet=True)
        if not interp._evaluator.components and interp._evaluator.app_decl is None:
            raise DeployError(f"{ui} has no components")
        UICompiler(output_dir=out, endpoints=endpoints_from_backend(backend_main)).compile(interp._evaluator)


def stage(workspace, name: str) -> Path:
    """Write the Vercel project to <workspace>/.mcn/deploy/<name>/ and return its path."""
    ws = Path(workspace).resolve()
    backend = ws / "backend"
    if not list(backend.rglob("*.mcn")):
        raise DeployError(f"No backend/*.mcn in {ws}. Vercel deploys need a backend with a service.")
    if not any("service " in f.read_text(encoding="utf-8") for f in backend.rglob("*.mcn")):
        raise DeployError("The backend has no `service` block, so there's no API to deploy")
    name = re.sub(r"[^a-z0-9-]+", "-", name.lower()).strip("-") or "mcn-app"
    out = ws / ".mcn" / "deploy" / name
    out.mkdir(parents=True, exist_ok=True)
    for child in out.iterdir():               # keep .vercel (the link to the Vercel project)
        if child.name != ".vercel":
            shutil.rmtree(child) if child.is_dir() else child.unlink()

    shutil.copytree(backend, out / "backend", ignore=shutil.ignore_patterns("*.db", "*.log", "__pycache__"))

    ui = ws / "ui" / "app.mcn"
    has_frontend = False
    if ui.exists():
        _compile_ui(ui, out / "frontend", backend / "main.mcn")
        has_frontend = True
    elif (ws / "frontend" / "package.json").exists():
        shutil.copytree(ws / "frontend", out / "frontend",
                        ignore=shutil.ignore_patterns("node_modules", "dist", "*.log"))
        has_frontend = True
    if has_frontend:
        (out / "frontend" / ".env.production").write_text("VITE_API_URL=/api\n", encoding="utf-8")

    (out / "api").mkdir()
    (out / "api" / "index.py").write_text(API_INDEX, encoding="utf-8")
    (out / "requirements.txt").write_text(f"mcn-lang[postgres] @ {SOURCE}\n", encoding="utf-8")
    (out / "vercel.json").write_text(json.dumps(_vercel_json(has_frontend), indent=2) + "\n", encoding="utf-8")
    (out / ".vercelignore").write_text("frontend/node_modules\nfrontend/dist\n*.db\n", encoding="utf-8")
    return out


def _project_env(ws: Path) -> Dict[str, str]:
    """The deployment's settings: forwarded keys from the project's .env, plus a stable auth secret."""
    env: Dict[str, str] = {}
    dotenv = ws / ".env"
    if dotenv.exists():
        for line in dotenv.read_text(encoding="utf-8").splitlines():
            key, sep, value = line.strip().partition("=")
            if sep and key.strip() in FORWARDED and value.strip():
                env[key.strip()] = value.strip().strip('"').strip("'")
    secret_file = ws / ".mcn" / "deploy" / "auth_secret"
    if not secret_file.exists():
        secret_file.parent.mkdir(parents=True, exist_ok=True)
        secret_file.write_text(secrets.token_hex(32), encoding="utf-8")
        os.chmod(secret_file, 0o600)
    env["MCN_AUTH_SECRET"] = secret_file.read_text(encoding="utf-8").strip()   # tokens stay valid across instances
    return env


def vercel_command() -> List[str]:
    if shutil.which("vercel"):
        return ["vercel"]
    if shutil.which("npx"):
        return ["npx", "--yes", "vercel@latest"]
    raise DeployError("Deploying to Vercel needs Node.js (for the Vercel CLI). Install it from https://nodejs.org")


def deploy(workspace, name: str, prod: bool = False, token: Optional[str] = None,
           interactive: bool = True, log=print) -> Dict[str, object]:
    """Stage the project and upload it. Returns {url, folder, env}."""
    ws = Path(workspace).resolve()
    out = stage(ws, name)
    env = _project_env(ws)
    token = token or os.environ.get("VERCEL_TOKEN")
    if not interactive and not token:
        raise DeployError("Set a VERCEL_TOKEN first (create one at https://vercel.com/account/tokens)")
    cmd = vercel_command() + ["deploy", "--yes"]
    if prod:
        cmd.append("--prod")
    for key, value in env.items():
        cmd += ["--env", f"{key}={value}"]
    if token:
        cmd += ["--token", token]
    log(f"Deploying {out.name} to Vercel (settings: {', '.join(sorted(env))})…")
    proc = subprocess.run(cmd, cwd=out, stdout=subprocess.PIPE, text=True,
                          stdin=None if interactive else subprocess.DEVNULL,
                          stderr=None if interactive else subprocess.PIPE)
    urls = re.findall(r"https://[^\s]+\.vercel\.app", proc.stdout or "")
    if proc.returncode != 0 or not urls:
        detail = (proc.stderr or "").strip().splitlines()[-3:] if not interactive else []
        raise DeployError("Vercel didn't finish the deployment" + (": " + " ".join(detail) if detail else ""))
    return {"url": urls[-1], "folder": str(out), "env": sorted(env)}
