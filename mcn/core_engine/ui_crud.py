"""
Frontend half of contract-driven CRUD: `crud_table Lead` in a render block.

The compiler writes two plain, readable files into the generated project:

  src/models.ts                 one Resource per contract (fields, endpoints)
  src/components/CrudTable.tsx  generic table + search + filter + sort +
                                pagination + add/edit dialog + delete confirm

and renders <CrudTable resource={LeadResource} ... /> where crud_table is used.
"""

from __future__ import annotations

import json
from typing import Dict, List

from .crud import crud_names, plural

# shadcn/ui components used by CrudTable.tsx
CRUD_SHADCN = ["badge", "button", "card", "dialog", "input", "label",
               "select", "switch", "table", "textarea"]


def _label(name: str) -> str:
    """follow_up → Follow up."""
    text = name.replace("_", " ").strip()
    return text[:1].upper() + text[1:]


def resource_ts(contract) -> str:
    names = crud_names(contract.name)
    fields = []
    for s in contract.specs:
        f: Dict = {"name": s.name, "label": _label(s.name), "type": s.type,
                   "required": s.required}
        if s.choices:
            f["choices"] = s.choices
            f["pluralLabel"] = _label(plural(s.name))      # "All priorities"
        if s.has_default and s.default is not None:
            f["default"] = s.default
        if s.unique:
            f["unique"] = True
        fields.append(f)
    resource = {
        "name": contract.name,
        "label": _label(names["singular"]),
        "plural": _label(names["plural"]),
        "endpoints": {k: f"/{names[k]}" for k in ("list", "get", "create", "update", "delete")},
        "fields": fields,
    }
    body = json.dumps(resource, indent=2, ensure_ascii=False)
    return f"export const {contract.name}Resource: Resource = {body}\n"


def models_ts(contracts: List) -> str:
    parts = [MODELS_HEADER]
    for c in contracts:
        parts.append(resource_ts(c))
    return "\n".join(parts)


MODELS_HEADER = '''\
/**
 * Data models — generated by `mcn build` from your MCN contracts.
 * Edit the contract in your .mcn file and rebuild; don't edit this file.
 */

export type FieldType =
  | "str" | "string" | "text" | "int" | "float" | "number"
  | "bool" | "date" | "datetime" | "choice" | "any"

export interface Field {
  name: string
  label: string
  type: FieldType | string
  required: boolean
  choices?: string[]
  pluralLabel?: string
  default?: unknown
  unique?: boolean
}

export interface Resource {
  name: string
  label: string
  plural: string
  endpoints: { list: string; get: string; create: string; update: string; delete: string }
  fields: Field[]
}
'''


