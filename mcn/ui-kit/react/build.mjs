// Builds the files Studio's live preview loads, into mcn/web-playground/static/preview/:
//   mcn-ui.js         every kit module, registered by the import path generated code uses
//   mcn-transform.js  TypeScript/JSX → JavaScript in the browser (sucrase)
//   mcn-ui.css        Tailwind styles for the kit and compiler output
//   react.js, react-dom.js
// The outputs are committed, so developers never need Node. Run: npm run build
import { build } from "esbuild"
import { execSync } from "node:child_process"
import { copyFileSync, mkdirSync, readdirSync, writeFileSync, rmSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, "../../web-playground/static/preview")
mkdirSync(out, { recursive: true })

execSync("node gen-icons.mjs", { cwd: here, stdio: "inherit" })

// React comes from the separate UMD files (window.React / window.ReactDOM)
const globals = {
  name: "react-globals",
  setup(b) {
    b.onResolve({ filter: /^react(-dom)?(\/client)?$/ }, (a) => ({ path: a.path, namespace: "global" }))
    b.onLoad({ filter: /.*/, namespace: "global" }, (a) => ({
      contents: `module.exports = window.${a.path.startsWith("react-dom") ? "ReactDOM" : "React"}`,
    }))
  },
}

// Registry entry: import every module and expose it under its generated-code path
const uiDir = join(here, "src/components/ui")
const files = readdirSync(uiDir).filter((f) => /\.tsx?$/.test(f) && f !== "icons-data.ts")
const entry = [
  `import * as utils from "./src/lib/utils"`,
  ...files.map((f, i) => `import * as m${i} from "./src/components/ui/${f.replace(/\.tsx?$/, "")}"`),
  `window.MCNUI = { modules: {`,
  `  "@/lib/utils": utils,`,
  ...files.map((f, i) => `  "@/components/ui/${f.replace(/\.tsx?$/, "")}": m${i},`),
  `} }`,
].join("\n")
const entryFile = join(here, ".preview-entry.js")
writeFileSync(entryFile, entry)

const common = { bundle: true, format: "iife", minify: true, target: "es2019", logLevel: "warning" }
await build({
  ...common, entryPoints: [entryFile], outfile: join(out, "mcn-ui.js"),
  plugins: [globals], jsx: "transform", jsxFactory: "React.createElement", jsxFragment: "React.Fragment",
  alias: { "@": join(here, "src") }, banner: { js: "/* MCN UI kit — generated by mcn/ui-kit/react/build.mjs */" },
})
rmSync(entryFile)

await build({
  ...common, stdin: {
    contents: `import { transform } from "sucrase"
      window.MCNTransform = (code, filePath) => transform(code, {
        transforms: ["typescript", "jsx", "imports"], jsxRuntime: "classic", production: true, filePath,
      }).code`,
    resolveDir: here,
  },
  outfile: join(out, "mcn-transform.js"),
})

execSync(`npx tailwindcss -c tailwind.config.js -i src/preview.css -o "${join(out, "mcn-ui.css")}" --minify`, { cwd: here, stdio: "inherit" })

copyFileSync(join(here, "node_modules/react/umd/react.production.min.js"), join(out, "react.js"))
copyFileSync(join(here, "node_modules/react-dom/umd/react-dom.production.min.js"), join(out, "react-dom.js"))
console.log(`preview assets → ${out}`)
